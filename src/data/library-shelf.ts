/**
 * Ancestors — a shelf of fifty works from the Source Library (sourcelibrary.org),
 * the digitised collection of the Embassy of the Free Mind, read as early
 * versions of what the rest of the Atlas works on.
 *
 * The books were found by running concept queries against the library's
 * semantic index rather than keyword search, because none of these texts use
 * the words quantum, artificial intelligence, robot or foresight. Titles,
 * authors, dates, cover plates and the `description` lines are the library's
 * own metadata; `note`, `tags`, the categories and the edges are the curation.
 *
 * `edges` are undirected: each pair renders on BOTH cards, with the same line
 * saying why the two read together.
 */

export type ShelfCategoryKey =
  | "reasoning"
  | "automata"
  | "physics"
  | "forecast"
  | "worlds";

export interface ShelfCategory {
  key: ShelfCategoryKey;
  /** heading on the section */
  name: string;
  /** filter chip label */
  short: string;
  blurb: string;
}

export interface ShelfBook {
  /** Source Library book id, and the anchor for cross references */
  id: string;
  cat: ShelfCategoryKey;
  title: string;
  /** the title page's own words, when they differ from the English one */
  originalTitle?: string;
  author: string;
  year?: number;
  language?: string;
  pages?: number;
  /** slug on sourcelibrary.org */
  slug: string;
  /** cover plate, served by the library's image host */
  thumbnail: string;
  /** why it is on this shelf */
  note: string;
  /** the library's own summary line */
  description?: string;
  tags: string[];
}

/** [book id, book id, why they read together] — undirected. */
export type ShelfEdge = [string, string, string];

