/**
 * Wraps the bumper bench (tools/bumpers/index.html and grid.html) into a module
 * the /bumpers route handlers can import, the same way gen-logo-animator.mjs
 * does for /logo-animator: a page in public/ would skip the editor gate.
 *
 * Each page comes out self-contained. The scripts it loads, the logo engine
 * and site-art.js are inlined; field.js and the Archivo font are already
 * public, so those point at their live copies.
 *
 * Edit the files in tools/bumpers/, then `npm run gen:bumpers`. build/gen.js is
 * committed (node tools/bumpers/build-gen.mjs rebuilds it).
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dir = path.join(root, "tools/bumpers");
const read = (p) => fs.readFileSync(path.join(root, p), "utf8");
const inline = (js) => "<script>\n" + js.replace(/<\/script/gi, "<\\/script") + "\n</script>";

const animator = read("tools/logo-animator/index.html");
const engine = animator.slice(animator.indexOf("// >>> ENGINE"), animator.indexOf("// <<< ENGINE") + "// <<< ENGINE".length);
if (!engine.startsWith("// >>> ENGINE")) throw new Error("gen-bumpers: engine markers not found in the logo animator");

const sources =
  inline("window.BUMPER_ENGINE = " + JSON.stringify(engine) + ";\nwindow.BUMPER_SITEART = " + JSON.stringify(read("dataviz/templates/site-art.js")) + ";") + "\n" +
  inline(read("tools/bumpers/build/gen.js")) + "\n" +
  inline(read("tools/bumpers/bumper.js"));

function page(file) {
  let html = fs.readFileSync(path.join(dir, file), "utf8");
  const swap = (from, to) => {
    if (!html.includes(from)) throw new Error(`gen-bumpers: ${file} no longer contains ${from}`);
    html = html.split(from).join(to);
  };
  swap("../../dataviz/fonts/Archivo-VF.ttf", "/futures-in-figures/charts/fonts/Archivo-VF.ttf");
  swap('<script src="../../public/interference/field.js"></script>', '<script src="/interference/field.js"></script>');
  swap('<script src="build/gen.js"></script>\n<script src="bumper.js"></script>', sources);
  return html;
}

let index = page("index.html");
index = index.replace('href="grid.html"', 'href="/bumpers/grid"');
let grid = page("grid.html");
grid = grid.replace('open("./?" + q, "_blank")', 'open("/bumpers?" + q, "_blank")');

const out = path.join(root, "src/generated/bumpers.ts");
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out,
  "// GENERATED by scripts/gen-bumpers.mjs — do not edit.\n" +
  "// Source: tools/bumpers/ · run `npm run gen:bumpers`.\n" +
  "export const BUMPERS_HTML = " + JSON.stringify(index) + ";\n" +
  "export const BUMPERS_GRID_HTML = " + JSON.stringify(grid) + ";\n");

console.log(`gen-bumpers: ${((index.length + grid.length) / 1024).toFixed(0)} kB → src/generated/bumpers.ts`);
