#!/usr/bin/env node
/**
 * Copy the Futures in Figures charts from dataviz/ into
 * public/futures-in-figures/charts/, so /futures-in-figures can show them live.
 *
 *   node scripts/sync-futures-in-figures.mjs
 *
 * The site page embeds each chart's own page in web mode
 * (charts/output/<slug>/index.html?slide=hook&format=web&v=field): the same
 * code and the same cleaned data that make the posts. Folder layout is kept,
 * because the chart pages load ../../templates and ../../data relatively.
 * Only what the charts load at runtime is copied, never raw sources.
 * Run it after changing a chart, then commit the result.
 */
import { cpSync, mkdirSync, rmSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(ROOT, "dataviz");
const OUT = join(ROOT, "public/futures-in-figures/charts");
const PIECES = ["q-day", "qubits-vs-quality", "training-compute"];
const DATA = {
  "q-day": ["clean.csv"],
  "qubits-vs-quality": ["clean.csv"],
  "training-compute": ["clean.csv", "clean-frontier.csv"],
};

rmSync(OUT, { recursive: true, force: true });
const copy = (rel) => {
  mkdirSync(dirname(join(OUT, rel)), { recursive: true });
  cpSync(join(SRC, rel), join(OUT, rel));
};
for (const f of ["frame.js", "frame.css", "site-art.js", "variants.js"]) copy(`templates/${f}`);
for (const f of ["d3.min.js", "fa.svg"]) copy(`vendor/${f}`);
copy("fonts/Archivo-VF.ttf"); // frame.css declares it; the site theme itself uses system sans
for (const p of PIECES) {
  copy(`output/${p}/index.html`);
  for (const f of DATA[p]) copy(`data/${p}/${f}`);
}
// method notes and the cleaned data, linked from the page as "Method note" and "Data"
for (const p of PIECES) copy(`data/${p}/METHOD.md`);

// the reference list, generated by dataviz/build-references.mjs from Crossref
// records and the source details stored with the data; never edited by hand
const refs = JSON.parse(readFileSync(join(SRC, "references.json"), "utf8"));
writeFileSync(
  join(ROOT, "src/data/futures-in-figures-references.ts"),
  `// GENERATED by scripts/sync-futures-in-figures.mjs from dataviz/references.json. Do not edit.\n` +
    `// Rebuild: cd dataviz && node build-references.mjs, then node scripts/sync-futures-in-figures.mjs\n\n` +
    `export type FigureRef = { authors: string; year: number | string; title: string; venue: string; volume: string; pages: string; doi: string; url: string; pdf?: string; openAccess?: string; type: string; plotted: boolean; uses: { what: string; where: string }[] };\n\n` +
    `export const ACCESSED = ${JSON.stringify(refs.accessed)};\n\n` +
    `export const REFERENCES: Record<string, FigureRef[]> = ${JSON.stringify(Object.fromEntries(PIECES.map((p) => [p, refs[p]])), null, 2)};\n`,
);
console.log(`→ ${PIECES.length} charts synced to public/futures-in-figures/charts/, references to src/data/futures-in-figures-references.ts`);
