/**
 * Wraps tools/logo-animator/index.html into a module the app can import.
 *
 * The animator is one self-contained page of canvas drawing with no React in
 * it, and it must stay behind the editor gate, so it cannot live in public/ —
 * the middleware matcher skips anything with a file extension. Serving it from
 * a route handler keeps it gated; this turns the file into something that
 * handler can import.
 *
 * Edit tools/logo-animator/index.html (it opens straight in a browser), then
 * run `npm run gen:logo-animator`.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const src = path.join(root, "tools/logo-animator/index.html");
const out = path.join(root, "src/generated/logo-animator.ts");

const html = fs.readFileSync(src, "utf8");
fs.writeFileSync(out,
  "// GENERATED by scripts/gen-logo-animator.mjs — do not edit.\n" +
  "// Source: tools/logo-animator/index.html · run `npm run gen:logo-animator`.\n" +
  "export const LOGO_ANIMATOR_HTML = " + JSON.stringify(html) + ";\n");

console.log(`gen-logo-animator: ${(html.length / 1024).toFixed(1)} kB → src/generated/logo-animator.ts`);
